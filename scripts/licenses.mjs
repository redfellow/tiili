// Writes THIRD_PARTY_LICENSES.md: every third-party package the tiili app ships, with its licence.
//
//   npm run licenses
//
// It lists the frontend's npm packages (package-lock.json entries that are not dev-only) and the Rust crates
// compiled into the app on any platform (`cargo tree`, normal dependencies, without proc macros, which run only
// at build time). The bundled fonts and the Heynote build keep their own lists, linked from the file.
// Run it again after changing dependencies.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cell = (text) => String(text ?? "").replace(/\|/g, "\\|");

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  return Object.entries(lock.packages)
    .filter(([path, entry]) => path.startsWith("node_modules/") && !entry.dev && !entry.devOptional)
    .map(([path, entry]) => ({
      name: path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length),
      version: entry.version,
      license: entry.license ?? "see package",
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function crates() {
  const out = execFileSync(
    "cargo",
    [
      "tree",
      "--manifest-path",
      join(root, "src-tauri", "Cargo.toml"),
      "--locked",
      "-e",
      "normal",
      "--target",
      "all",
      "--prefix",
      "none",
      "--format",
      "{p}|{l}",
    ],
    { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
  );
  const found = new Map();
  for (const line of out.split("\n")) {
    if (!line.trim() || line.includes("(proc-macro)")) continue;
    const [spec, license] = line.replace(" (*)", "").split("|");
    // `name v1.2.3` or `name v1.2.3 (/path)` for the app's own crate.
    const [name, version, local] = spec.trim().split(" ");
    if (local || name === "tiili") continue;
    found.set(`${name} ${version}`, { name, version: version.replace(/^v/, ""), license: license || "unknown" });
  }
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

const table = (rows) =>
  "| Package | Version | Licence |\n| --- | --- | --- |\n" +
  rows.map((row) => `| ${cell(row.name)} | ${cell(row.version)} | ${cell(row.license)} |`).join("\n");

const npm = npmPackages();
const rust = crates();
writeFileSync(
  join(root, "THIRD_PARTY_LICENSES.md"),
  "# Third-party licences\n\n" +
    "tiili itself is [MIT](LICENSE). The app ships the third-party code below, each under its own licence; " +
    "the full licence texts are in each package's source (npm package or crates.io crate). " +
    "Generated by `npm run licenses`.\n\n" +
    "- Bundled fonts (SIL Open Font License 1.1): [`src/assets/fonts/LICENSES.md`](src/assets/fonts/LICENSES.md)\n" +
    "- Heynote (MIT with the Commons Clause) and the code bundled with it: " +
    "[`public/heynote/LICENSE`](public/heynote/LICENSE), [`public/heynote/THIRD_PARTY.md`](public/heynote/THIRD_PARTY.md)\n\n" +
    `## Frontend npm packages (${npm.length})\n\n` +
    table(npm) +
    `\n\n## Rust crates (${rust.length})\n\nCompiled into the app on macOS, Windows or Linux.\n\n` +
    table(rust) +
    "\n",
);
console.log(`THIRD_PARTY_LICENSES.md: ${npm.length} npm packages, ${rust.length} crates`);
